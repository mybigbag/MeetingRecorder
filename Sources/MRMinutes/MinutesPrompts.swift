import Foundation

/// 纪要提示词的**唯一出处**。
///
/// 本地 `FoundationModelsMinutesGenerator` 与云端 `CloudAPIMinutesGenerator`
/// 共用这里的文本。分成两份各写一遍的话，两边对「绝不编造」「负责人未提及填空」
/// 这类关键约束的表达迟早会漂——而用户拿两份纪要对照时，没有任何机制能发现
/// 「同样的输入，两个实现被嘱咐了不同的事」。
///
/// ## 为什么这里有一整套「规范」，而不是几句嘱咐
///
/// 第一版提示词只说「列出讨论要点、达成的决议、产生的待办」。结果**必然**是
/// 一堆会议内容罗列：`keyPoints: [String]` 这种平铺结构加上「列出」这个动词，
/// 模型能做的只有把发言一条条摘出来。用户拿到的「纪要」读起来像压缩过的
/// 转写稿——没有结论、没有取舍，还得自己再总结一遍。
///
/// 所以规范必须具体到可执行：
/// - **结构**上给「议题 → 结论」的关系（`MeetingTopic`），不让模型平铺；
/// - **语言**上禁掉叙述句（「某某说」「然后」），只允许判断与事实；
/// - **边界**上把「讨论中的观点 / 已达成的决议 / 还没定的事」分开，
///   否则读者会拿「还没定」去执行；
/// - **纠错**上明确四类可改、三类依据、以及「拿不准保留原词」——
///   语音识别的错字不纠正，纪要里就会出现莫名其妙的内容；而放开让模型
///   「通顺化」，它就会补出没说过的话。这两者的界线必须写死在提示词里。
///
/// ## 分层
///
/// - `coreRules`：两个实现**必须一致**的硬约束（纠错边界、不编造、不罗列）；
/// - `detailedSpec`：给云端的长规范（结构、语言、长度），本地 4096 上下文装不下；
/// - 各阶段的输出契约：本地由 `@Generable` 在编译期约束，云端必须写死 JSON 字段名。
enum MinutesPrompts {

    // MARK: - 共用硬约束（两个实现都必须遵守）

    /// 纠错与不编造的硬约束。**改动这里等于同时改动两个实现的行为**。
    static let coreRules = """
        【硬性约束，违反任何一条即视为输出无效】
        1. 先纠错再整理。转写稿来自语音识别，只纠正四类错误：同音/近音错字、
           专有名词（产品名、系统名、人名、英文术语）、数字与单位、断句造成的词义扭曲。
        2. 纠错必须有依据，依据只有三种：后文出现了正确写法、同一场会议反复出现同一写法、
           与上下文语义唯一吻合的行业术语。没有依据就不要改。
        3. 只改词，不改意思。不得增删句子，不得把听不清的片段补写成通顺的话，
           不得改动数字、金额、结论与说话人的立场。拿不准就保留原词——
           宁可留一个错字，也不要造一句没说过的话。
        4. 只写转写稿里确实出现过的内容。不推断动机、不补充背景、不替发言人下结论；
           负责人、截止时间、数字未提及就留空，绝不编造。
        5. 不写叙述句。禁止「某某说……」「然后讨论到……」「接着……」这类摘录式表达；
           同一件事的多段发言必须合并成一条结论。
        6. 数字、日期、版本号、指标、系统名、人名、金额原样保留，不换算、不四舍五入。
        7. 转写稿里的「我」「对方」是**录音轨道的代称，不是人名**。不得把「对方」写成人名
           （不要出现「对方负责」「由对方和小林一起做」这类表述）：只写能确认的姓名，
           未具名的一侧留空；需要指代时用「另一侧」，或直接改成无主语的陈述。
        """

    /// 转写纠错规则的单行摘要（用在紧凑 prompt 里，内容与 `coreRules` 一致）。
    private static let compactCorrectionRule = """
        转写稿来自语音识别：先纠正同音/近音错字、专有名词、数字单位、断句造成的词义扭曲；
        依据只能是后文正确写法、同场重复写法或与上下文唯一吻合的术语；没依据不改，
        拿不准保留原词。只改词不改意，不增删句子、不补写听不清的内容、不改数字与结论。
        每处纠正要记录原词与改后的词。
        """

    // MARK: - 云端专用：完整纪要规范

    /// 「什么叫纪要」的完整规范。**云端专用**（本地 4096 上下文装不下）。
    static let detailedSpec = """
        【会议纪要规范】
        纪要是给人做决定用的文档，不是转写稿的缩写、也不是发言摘录。必须做到：

        一、结论先行
        先回答「这场会定了什么」，再交代怎么谈的。禁止按时间顺序复述。
        摘要的第一句就要能让没参会的人知道结论。

        二、以议题为单位，不以发言为单位
        同一件事的多段发言合并成一个议题，写成「议题 → 结论 → 支撑事实」。
        不要一人一条地摘录，也不要把一个议题拆成多条同义项。

        三、区分三类内容
        - 已决议：明确拍板、可以照着执行的事；
        - 未决：讨论了但没定、或要等上级/外部决定的事；
        - 讨论中的观点：只是有人提过，既不是决议也不是待办。
        提议、设想、「要不要」「可以考虑」一律不得写进决议。

        四、内容必须能被单独读懂
        每条是一个完整的判断或事实，读者不看上下文也明白。
        禁止语气词、口头禅、寒暄、场面话（「好的」「那个」「我们再看一下」）。

        五、语言
        书面中文、第三人称、陈述句。不用「我们觉得」「大家表示」「会上强调」这类套话，
        直接写结论本身。能用短句就不用长句。

        六、宁缺勿滥
        某一栏没有实质内容就留空数组。**为了填满栏目而编内容，比留空危险得多。**
        """

    // MARK: - map（单块）

    /// map 阶段的指令正文。两个实现共用。
    static let blockInstruction = """
        这是会议录音转写稿的一个分段（只是整场会议的一部分，不要假设它包含全部信息），
        格式为「说话人：内容」。请先按硬性约束纠错，再输出这一段的处理结果。

        \(coreRules)

        本段输出要求：
        1) polishedText：纠错、补全标点、按语义断句分段后的正文。保留「说话人：」标签；
           只补标点与分段，不合并不删减不概括，数字与专名用纠正后的写法。
        2) summary：一句话说明这一段在谈什么事（不是复述内容，也不要写「本段讨论了」）。
        3) keyPoints：这一段的关键信息，每条一句结论或事实，最多 5 条；
           必须带上具体数字、对象与结论，不要写「讨论了 XX 问题」这种空话。
        4) decisions：这一段里**已经明确**的决议。提议、设想、待确认的一律不写。
        5) actionItems：这一段产生的待办。负责人、截止时间未提及就填空字符串，不要编造。
        6) corrections：本段纠正过的识别错误，逐条给出原词、纠正后的词、一句话依据。
        """

    /// 本地模型的完整 prompt（单字符串，FoundationModels 的 `respond(to:)` 形态）。
    ///
    /// **比云端短**：本地上下文只有 4096 token，而一块最多 3000 token 输入——
    /// 完整规范塞进去会把正文挤掉，模型只能看到半段话还硬要输出摘要。
    /// 这里保留 `coreRules` 里最关键的纠错与不编造约束，删掉结构规范
    /// （本地版由 `@Generable` 的 `@Guide` 约束字段，本来也不需要文字说明）。
    static func blockPrompt(text: String) -> String {
        """
        这是会议转写稿的一个分段（只是整场会议的一部分），格式为「说话人：内容」。
        \(compactCorrectionRule)

        「我」「对方」是录音轨道的代称，不是人名：不要把「对方」当负责人或人名写进纪要，
        只写能确认的姓名，未具名的一侧留空。

        请输出：补全标点分段后的正文（保留说话人标签，不合并不概括）、
        一句话说明本段在谈什么、最多 5 条关键结论（带具体数字与对象）、
        本段已明确的决议（提议不算）、本段待办（负责人与时间未提及就留空）。

        分段文本：
        \(text)
        """
    }

    /// 云端模型的 system 角色。与本地版共用同一套指令，见 `blockUserPrompt`。
    static let systemRole = """
        你是一位资深会议秘书，负责把语音识别的会议转写稿整理成可直接发给未参会者的纪要。
        你只依据给定的转写稿工作：不做推断、不补充背景、不编造任何未出现的信息。
        """

    /// 云端 map 阶段的 user 消息：共用指令 + JSON 契约 + 数据。
    static func blockUserPrompt(text: String) -> String {
        """
        \(blockInstruction)

        严格输出一个 JSON 对象，不要输出任何其它文字，不要使用 Markdown 代码围栏。字段：
        {"polishedText": 字符串（纠错并补全标点后的正文）,
         "summary": 字符串,
         "keyPoints": 字符串数组,
         "decisions": 字符串数组,
         "actionItems": [{"task": 字符串, "owner": 字符串, "due": 字符串}],
         "corrections": [{"original": 字符串, "corrected": 字符串, "reason": 字符串}]}
        数组没有内容时输出空数组；owner/due 未提及时输出空字符串；
        corrections 没有纠正时输出空数组，不要为了凑数把没改的词也列进去。

        分段文本：
        \(text)
        """
    }

    // MARK: - reduce（合并）

    /// reduce 阶段的指令正文。两个实现共用。
    static let mergeInstruction = """
        下面是同一场会议各分段的局部摘要（按时间顺序）。请综合成整场会议的全局纪要。

        \(coreRules)

        \(detailedSpec)

        输出要求：
        1) summary：2-5 句。写清三件事——这是什么会、就得出的结论是什么、下一步是什么。
           **不要**用「本次会议围绕……展开了讨论」这类没有信息的开头。
        2) topics：按重要性排序的议题，2-6 个。每个议题包含：
           - title：名词短语，指向一件事（如「Q4 排期」「支付模块上线风险」）；
           - conclusion：一句话结论。定了什么就写定论；没定就写「未定：分歧在 X」；
             不要把讨论过程写进 conclusion；
           - details：0-3 条支撑结论的事实、数据、分歧点。没有具体内容就留空数组，
             不要写「与会人员进行了深入讨论」这种填充句。
        3) decisions：明确拍板的决定，每条可独立执行。提议、待确认、将继续讨论的一律不写。
        4) actionItems：合并各段相同的项；负责人、截止时间未提及填空字符串。
        5) openIssues：讨论过但没有结论、或需要上级/外部决定的事。没有就留空数组。

        合并时的判断：如果几段局部要点其实是同一件事的不同说法，合并成一条；
        如果互相矛盾（前后说法不一致），在对应议题的 details 里写明「前后说法不一致：……」，
        不要擅自选一个当成结论。
        """

    /// 本地模型的完整 prompt（单字符串形态）。同样为 4096 上下文压缩。
    static func mergePrompt(joinedSummaries: String) -> String {
        """
        下面是同一场会议各分段的局部摘要。请综合成整场会议纪要。

        \(compactCorrectionRule)

        要求：
        1) 摘要 2-5 句：什么会、得出了什么结论、下一步是什么；不要写「围绕……展开讨论」。
        2) 议题按重要性排 2-6 个，每个给出标题、一句结论、最多 3 条支撑事实；
           没定的事写「未定：分歧在 X」，不要把讨论过程当结论。
        3) 决议只写明确拍板的事，提议不算；待办合并重复项，负责人与时间未提及留空。
        4) 未决事项单独列出：讨论过但没定、或要等外部决定的事。
        5) 同一件事的不同说法要合并；前后矛盾时写明不一致，不要擅自选一个。

        \(joinedSummaries)
        """
    }

    /// 云端 reduce 阶段的 user 消息：共用指令 + JSON 契约 + 数据。
    static func mergeUserPrompt(joinedSummaries: String) -> String {
        """
        \(mergeInstruction)

        严格输出一个 JSON 对象，不要输出任何其它文字，不要使用 Markdown 代码围栏。字段：
        {"summary": 字符串,
         "topics": [{"title": 字符串, "conclusion": 字符串, "details": 字符串数组}],
         "decisions": 字符串数组,
         "actionItems": [{"task": 字符串, "owner": 字符串, "due": 字符串}],
         "openIssues": 字符串数组}
        数组没有内容时输出空数组；owner/due 未提及时输出空字符串。
        topics 至少 1 个（会议只谈了一件事就只给 1 个）。

        \(joinedSummaries)
        """
    }

    // MARK: - 局部摘要的渲染（reduce 的输入）

    /// 把各块局部摘要渲染成 reduce 阶段的输入文本。
    ///
    /// 本地与云端两个实现的 merge 都吃这份渲染结果。各写一遍的话，
    /// 「第 N 段」的格式、待办的括号说明、空数组的表现都会漂——
    /// 而用户拿两份纪要对不出差别来自哪。
    ///
    /// **纠错结果不在这里传**：各块的 `corrections` 由 `MinutesOrchestrator`
    /// 直接汇总成勘误表，不必让模型再抄一遍（抄写只会多一层出错机会）。
    static func renderSummaries(_ summaries: [BlockSummary]) -> String {
        summaries
            .sorted { $0.index < $1.index }
            .map { s -> String in
                let kp = s.keyPoints.joined(separator: "、")
                let dc = s.decisions.joined(separator: "、")
                let ai = s.actionItems
                    .map { "\($0.task)（负责人：\($0.owner.isEmpty ? "未指定" : $0.owner)；截止：\($0.due.isEmpty ? "未指定" : $0.due)）" }
                    .joined(separator: "；")
                return "[第\(s.index)段] 摘要：\(s.summary)\n要点：\(kp)\n决议：\(dc)\n待办：\(ai)"
            }
            .joined(separator: "\n\n")
    }
}
